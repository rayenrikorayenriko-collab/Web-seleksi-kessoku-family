-- 1) Generasi (angkatan)
create table if not exists public.generations (
  id text primary key default ('gen_' || substr(md5(random()::text), 1, 8)),
  name text not null,
  link text default '',
  members integer default 0,
  active boolean default true,
  created_at timestamptz default now()
);

-- 2) Hashtag TikTok
create table if not exists public.hashtags (
  tag text primary key,
  count integer default 0,
  created_at timestamptz default now()
);

-- 3) CN (bar CN di halaman daftar)
create table if not exists public.cns (
  id text primary key default ('cn_' || substr(md5(random()::text), 1, 8)),
  tpl text not null,
  created_at timestamptz default now()
);

-- 4) Pendaftaran member
create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  nama text,
  tiktok text,
  email text,
  gen text,
  alasan text,
  cns jsonb default '[]'::jsonb,
  cn1 text,
  cn2 text,
  cn3 text,
  joined_at timestamptz default now()
);

-- 5) Pengaturan (mis. total member manual)
create table if not exists public.app_settings (
  key text primary key,
  value jsonb
);

-- ================= RLS (Row Level Security) =================
alter table public.generations   enable row level security;
alter table public.hashtags      enable row level security;
alter table public.cns           enable row level security;
alter table public.registrations enable row level security;
alter table public.app_settings  enable row level security;

-- Baca publik (semua pengunjung boleh melihat angka/gen/hashtag)
create policy "read_all_generations" on public.generations  for select using (true);
create policy "read_all_hashtags"    on public.hashtags     for select using (true);
create policy "read_all_cns"         on public.cns          for select using (true);
create policy "read_all_settings"    on public.app_settings for select using (true);

-- Tulis (dipakai panel Setting dengan anon key).
-- CATATAN: anon key itu publik. Untuk komunitas ini biasanya cukup,
-- tapi siapa pun yang tahu URL + key bisa menulis. Lihat catatan "Hardening".
create policy "write_generations" on public.generations  for all    using (true) with check (true);
create policy "write_hashtags"    on public.hashtags     for all    using (true) with check (true);
create policy "write_cns"         on public.cns          for all    using (true) with check (true);
create policy "write_settings"    on public.app_settings for all    using (true) with check (true);

-- Pendaftaran: siapa pun boleh mengirim (insert), boleh dibaca panel
create policy "insert_registrations" on public.registrations for insert with check (true);
create policy "read_registrations"   on public.registrations for select using (true);

